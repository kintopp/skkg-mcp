// sha256 over everything the viewer build reads: the viewer sources, the build scripts, the licence texts it copies,
// and the installed versions of the packages it bundles and of vite and its dependencies. Stamped into the built page
// with the list of bundled packages, which only the build's module graph knows, and checked by
// test/viewer_build.test.js.

import { createHash } from 'node:crypto';
import { readFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { INLINED_BY_EXT_APPS, installedPackage, licenceText } from './viewer-licences.mjs';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const VIEWER_SRC_DIR = join(ROOT, 'apps', 'image-viewer');
export const VIEWER_HTML = join(ROOT, 'src', 'apps', 'image-viewer.html');
const BUILD_SCRIPTS = ['build-viewer.mjs', 'viewer-licences.mjs'];

const STAMP_RE = /^<!-- generated by npm run build:viewer; bundles (\S+(?: \S+)*); source sha256:([0-9a-f]{64}) -->/;
export const stamp = (bundled, hash) => `<!-- generated by npm run build:viewer; bundles ${bundled.join(' ')}; source sha256:${hash} -->`;

export function readStamp(html) {
  const m = STAMP_RE.exec(html);
  return m && { bundled: m[1].split(' '), hash: m[2] };
}

// vite pins its bundler and CSS minifier by range, so a lockfile refresh can change them without a vite bump.
const buildTools = () => ['vite', 'vite-plugin-singlefile', ...Object.keys(installedPackage('vite').dependencies ?? {})];

export function viewerSourceHash(bundled) {
  const h = createHash('sha256');
  const part = (label, bytes) => h.update(`${label}\0`).update(bytes).update('\0');
  for (const name of readdirSync(VIEWER_SRC_DIR).sort()) part(name, readFileSync(join(VIEWER_SRC_DIR, name)));
  for (const name of BUILD_SCRIPTS) part(`scripts/${name}`, readFileSync(join(ROOT, 'scripts', name)));
  const packages = [...bundled].sort();
  for (const name of [...packages, ...INLINED_BY_EXT_APPS]) part(`licence ${name}`, licenceText(name));
  for (const name of [...packages, ...buildTools()]) part('version', `${name}@${installedPackage(name).version}`);
  return h.digest('hex');
}
